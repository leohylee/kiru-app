export function getCharacterPool(scripts, charSets) {
  const pool = [];

  scripts.forEach((script) => {
    charSets.forEach((charSet) => {
      if (kanaData[script] && kanaData[script][charSet]) {
        pool.push(...kanaData[script][charSet]);
      }
    });
  });

  return pool;
}
